"""Which TimescaleDB HA images actually exist.

This is the part of the version story that can be *checked* rather than
believed: either the registry serves a tag for a given PostgreSQL/TimescaleDB
pair or it does not. So the catalog under ``data/images.json`` is generated by
querying the Docker registry, records the URL it came from, and is refreshed
with ``make images-refresh`` rather than edited by hand.

Nothing here infers compatibility. "An image exists" and "you may upgrade to it"
are different claims, and only the first one lives in this module.
"""

