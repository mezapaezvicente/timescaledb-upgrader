DEFAULT_REPOSITORY = "timescale/timescaledb-ha"

_AUTH_URL = "https://auth.docker.io/token?service=registry.docker.io&scope=repository:{repo}:pull"
_TAGS_URL = "https://registry-1.docker.io/v2/{repo}/tags/list?n=10000"

# Release tags look like  pg16.15-ts2.30.1[-p0][-all][-oss]
# Deliberately strict: it must not match the repository's cicd-*, *-builder,
# *-dev, *-latest or floating (pg16-ts2.30) tags, none of which pin a pair.
_RELEASE_TAG = re.compile(
    r"^pg(?P<pg>\d+\.\d+)-ts(?P<ts>\d+\.\d+\.\d+)"
    r"(?:-p(?P<patch>\d+))?"
    r"(?P<variant>(?:-(?:all|oss))*)$"
)

_USER_AGENT = "timescaledb-upgrader/0.1 (+https://github.com/)"


class RegistryError(Exception):
    """Raised when the registry cannot be queried.

    Always raised loudly. A registry that times out or refuses authentication
    must not be mistaken for a registry that has no such image.
    """


@dataclass(frozen=True)
class ImagePair:
    """One fully pinned (PostgreSQL, TimescaleDB) pair and its tags."""

    pg: str
    ts: str
    tags: Tuple[str, ...]

    @property
    def pg_major(self) -> int:
        return parse_version(self.pg)[0]

    @property
    def ts_series(self) -> Tuple[int, int]:
        parts = parse_version(self.ts)
        return (parts[0], parts[1] if len(parts) > 1 else 0)


def parse_release_tag(tag: str) -> Optional[Dict[str, str]]:
    """Parse a fully pinned release tag, or return None if it is not one."""
    match = _RELEASE_TAG.match(tag)
    if not match:
        return None
    return {
        "pg": match.group("pg"),
        "ts": match.group("ts"),
        "patch": match.group("patch") or "",
        "variant": match.group("variant") or "",
    }


def _get_json(url: str, headers: Dict[str, str], timeout: float) -> Any:
    request = urllib.request.Request(url, headers=headers)
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        raise RegistryError(
            "registry returned HTTP {0} for {1}".format(exc.code, url)
        ) from exc
    except urllib.error.URLError as exc:
        raise RegistryError("cannot reach {0}: {1}".format(url, exc.reason)) from exc
    except TimeoutError as exc:
        raise RegistryError("timed out after {0}s querying {1}".format(timeout, url)) from exc
    except json.JSONDecodeError as exc:
        raise RegistryError("registry returned non-JSON from {0}: {1}".format(url, exc)) from exc


def fetch_tags(
    repository: str = DEFAULT_REPOSITORY,
    timeout: float = 30.0,
) -> List[str]:
    """Fetch every tag for ``repository`` from the Docker registry.

    Uses the registry v2 API with an anonymous pull token. The Docker Hub web
    API is deliberately not used: it rejects deep pagination for anonymous
    callers, which silently truncates the result.
    """
    token_doc = _get_json(
        _AUTH_URL.format(repo=repository),
        {"User-Agent": _USER_AGENT},
        timeout,
    )
    token = token_doc.get("token")
    if not token:
        raise RegistryError(
            "registry issued no pull token for {0}".format(repository)
        )

    doc = _get_json(
        _TAGS_URL.format(repo=repository),
        {"Authorization": "Bearer " + token, "User-Agent": _USER_AGENT},
        timeout,
    )
    tags = doc.get("tags")
    if not isinstance(tags, list):
        raise RegistryError(
            "registry returned no tag list for {0}".format(repository)
        )
    return [str(t) for t in tags]


def build_catalog(tags: Sequence[str], repository: str = DEFAULT_REPOSITORY) -> Dict[str, Any]:
    """Group raw tags into the on-disk catalog structure."""
    grouped: Dict[Tuple[str, str], List[str]] = {}
    release_count = 0

    for tag in tags:
        parsed = parse_release_tag(tag)
        if parsed is None:
            continue
        release_count += 1
        grouped.setdefault((parsed["pg"], parsed["ts"]), []).append(tag)

    def sort_key(item: Tuple[Tuple[str, str], List[str]]):
        (pg, ts), _ = item
        return (parse_version(pg), parse_version(ts))

    pairs = [
        {"pg": pg, "ts": ts, "tags": sorted(tag_list)}
        for (pg, ts), tag_list in sorted(grouped.items(), key=sort_key)
    ]

    return {
        "schema_version": 1,
        "repository": repository,
        "source_url": _TAGS_URL.format(repo=repository),
        "queried_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "note": (
            "Generated by `make images-refresh`. Records which image tags exist, "
            "nothing about whether an upgrade between them is supported."
        ),
        "counts": {
            "tags_total": len(tags),
            "release_tags": release_count,
            "pairs": len(pairs),
        },
        "pairs": pairs,
    }


class ImageCatalog:
    """Queryable view over the generated image catalog."""

    def __init__(self, doc: Dict[str, Any]) -> None:
        self.doc = doc
        self.repository: str = doc.get("repository", DEFAULT_REPOSITORY)
        self.source_url: Optional[str] = doc.get("source_url")
        self.queried_at: Optional[str] = doc.get("queried_at")
        self.pairs: List[ImagePair] = [
            ImagePair(
                pg=str(p["pg"]),
                ts=str(p["ts"]),
                tags=tuple(p.get("tags", ())),
            )
            for p in doc.get("pairs", [])
            if "pg" in p and "ts" in p
        ]

    def __len__(self) -> int:
        return len(self.pairs)

    def pg_majors(self) -> List[int]:
        return sorted({p.pg_major for p in self.pairs})

    def ts_series_for(self, pg_major: int) -> List[Tuple[int, int]]:
        return sorted({p.ts_series for p in self.pairs if p.pg_major == pg_major})

    def latest_ts_series(self, pg_major: int) -> Optional[Tuple[int, int]]:
        series = self.ts_series_for(pg_major)
        return series[-1] if series else None

    def has_pair(self, pg: object, ts: object) -> bool:
        """Whether any image exists for a PostgreSQL major and TimescaleDB series."""
        try:
            want_pg = parse_version(pg)[0]
            ts_parts = parse_version(ts)
        except InvalidVersion:
            return False
        want_ts = (ts_parts[0], ts_parts[1] if len(ts_parts) > 1 else 0)
        return any(
            p.pg_major == want_pg and p.ts_series == want_ts for p in self.pairs
        )

    def tags_for(self, pg: object, ts: object) -> List[str]:
        """Every tag matching a PostgreSQL major and TimescaleDB series."""
        try:
            want_pg = parse_version(pg)[0]
            ts_parts = parse_version(ts)
        except InvalidVersion:
            return []
        want_ts = (ts_parts[0], ts_parts[1] if len(ts_parts) > 1 else 0)
        found: List[str] = []
        for pair in self.pairs:
            if pair.pg_major == want_pg and pair.ts_series == want_ts:
                found.extend(pair.tags)
        return sorted(found)


def default_catalog_path() -> Path:
    return Path(__file__).resolve().parents[2] / "data" / "images.json"


def load_catalog(path: Optional[object] = None) -> ImageCatalog:
    target = Path(path) if path is not None else default_catalog_path()
    try:
        doc = json.loads(target.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise RegistryError(
            "image catalog not found: {0} (run `make images-refresh`)".format(target)
        ) from exc
    except json.JSONDecodeError as exc:
        raise RegistryError("{0} is not valid JSON: {1}".format(target, exc)) from exc
    if not isinstance(doc, dict):
        raise RegistryError("{0}: expected a JSON object".format(target))
    return ImageCatalog(doc)


