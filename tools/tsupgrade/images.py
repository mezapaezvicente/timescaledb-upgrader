_DOCKER_HUB_HOSTS = {"docker.io", "index.docker.io", "registry-1.docker.io"}


def parse_image_reference(reference: str) -> Tuple[str, str, str]:
    """Split ``registry/repository:tag`` into its parts.

    Defaults follow the usual Docker conventions: no registry means Docker Hub,
    a single-segment repository on Docker Hub means ``library/``, and no tag
    means ``latest``.
    """
    ref = str(reference).strip()
    if not ref:
        raise RegistryError("empty image reference")
    if "@" in ref:
        # A digest pins the image outright; splitting it as a tag would be wrong.
        raise RegistryError(
            "digest-pinned references are not supported here: {0}".format(ref)
        )

    remainder = ref
    registry = "registry-1.docker.io"

    head, slash, tail = ref.partition("/")
    # A first segment is a registry only if it looks like a host.
    if slash and ("." in head or ":" in head or head == "localhost"):
        registry = head
        remainder = tail

    repository, colon, tag = remainder.rpartition(":")
    if not colon or "/" in tag:
        repository, tag = remainder, "latest"

    if not repository:
        raise RegistryError("no repository in image reference: {0}".format(ref))

    if registry in _DOCKER_HUB_HOSTS:
        registry = "registry-1.docker.io"
        if "/" not in repository:
            repository = "library/" + repository

    return registry, repository, tag


_MANIFEST_ACCEPT = ", ".join(
    [
        "application/vnd.oci.image.index.v1+json",
        "application/vnd.oci.image.manifest.v1+json",
        "application/vnd.docker.distribution.manifest.list.v2+json",
        "application/vnd.docker.distribution.manifest.v2+json",
    ]
)


def _parse_auth_challenge(header: str) -> Dict[str, str]:
    """Pull realm/service/scope out of a WWW-Authenticate: Bearer header."""
    fields: Dict[str, str] = {}
    if not header:
        return fields
    _, _, rest = header.partition(" ")
    for part in rest.split(","):
        key, _, value = part.strip().partition("=")
        if key:
            fields[key.strip()] = value.strip().strip('"')
    return fields


def mirrored(reference: str, registry: Optional[str]) -> str:
    """``reference`` on another registry, with its image name, tag and digest.

    ``registry`` is what comes before the image name, a host and any path:
    ``registry.example.com/dockerhub/timescale`` gives
    ``registry.example.com/dockerhub/timescale/timescaledb-ha:<tag>@<digest>``.
    The digest stays, so the mirror has to serve the very image that was
    verified, or the pull fails.
    """
    if not registry:
        return reference
    return "{0}/{1}".format(registry.rstrip("/"), reference.rsplit("/", 1)[-1])


def registry_problem(registry: str) -> Optional[str]:
    """Why ``registry`` cannot be used as ``--image-registry``, if it cannot."""
    if "://" in registry or "@" in registry:
        return "--image-registry takes a host and path, without a scheme or digest: {0}".format(registry)
    head = registry.split("/", 1)[0]
    if not ("." in head or ":" in head or head == "localhost"):
        return "--image-registry must start with a registry host: {0}".format(registry)
    return None


def node_image_name(reference: str) -> str:
    """How a Kubernetes node lists ``reference``: ``host/repo@digest``, or
    ``host/repo:tag`` without a digest, with Docker Hub as ``docker.io``."""
    name, _, digest = str(reference).strip().partition("@")
    registry, repository, tag = parse_image_reference(name)
    host = "docker.io" if registry == "registry-1.docker.io" else registry
    return "{0}/{1}@{2}".format(host, repository, digest) if digest else "{0}/{1}:{2}".format(host, repository, tag)


def manifest_exists(reference: str, timeout: float = 15.0) -> Tuple[bool, str]:
    """Whether the registry serves a manifest for ``reference``, by its digest
    when it has one.

    Returns ``(exists, detail)``. A missing tag is a normal ``False``; anything
    else -- a refused token, a network failure, a timeout -- raises
    ``RegistryError``. A registry that will not answer must never be recorded as
    a registry that has no such image.

    Every request carries an explicit timeout, so this fails loudly instead of
    hanging a maintenance window.
    """
    name, _, digest = str(reference).strip().partition("@")
    registry, repository, tag = parse_image_reference(name)
    tag = digest or tag
    url = "https://{0}/v2/{1}/manifests/{2}".format(registry, repository, tag)
    headers = {"Accept": _MANIFEST_ACCEPT, "User-Agent": _USER_AGENT}

    def attempt(extra: Optional[Dict[str, str]] = None):
        request = urllib.request.Request(url, headers=dict(headers, **(extra or {})))
        request.get_method = lambda: "GET"
        return urllib.request.urlopen(request, timeout=timeout)

    try:
        try:
            with attempt() as response:
                return response.status == 200, "{0} responded {1}".format(
                    registry, response.status
                )
        except urllib.error.HTTPError as exc:
            if exc.code != 401:
                raise
            # Standard registry auth: follow the Bearer challenge once.
            challenge = _parse_auth_challenge(exc.headers.get("WWW-Authenticate", ""))
            realm = challenge.get("realm")
            if not realm:
                raise RegistryError(
                    "{0} requires authentication and offered no token realm; "
                    "log in or supply credentials".format(registry)
                ) from exc

            query = []
            if challenge.get("service"):
                query.append("service=" + urllib.parse.quote(challenge["service"]))
            query.append(
                "scope="
                + urllib.parse.quote("repository:{0}:pull".format(repository))
            )
            token_url = realm + "?" + "&".join(query)
            token_doc = _get_json(token_url, {"User-Agent": _USER_AGENT}, timeout)
            token = token_doc.get("token") or token_doc.get("access_token")
            if not token:
                raise RegistryError(
                    "{0} issued no pull token for {1}".format(registry, repository)
                ) from exc

            with attempt({"Authorization": "Bearer " + token}) as response:
                return response.status == 200, "{0} responded {1}".format(
                    registry, response.status
                )

    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            return False, "{0} has no tag {1} for {2}".format(registry, tag, repository)
        if exc.code in (401, 403):
            raise RegistryError(
                "{0} refused access to {1}:{2} (HTTP {3}); this is an auth "
                "failure, not a missing image".format(
                    registry, repository, tag, exc.code
                )
            ) from exc
        raise RegistryError(
            "{0} returned HTTP {1} for {2}:{3}".format(
                registry, exc.code, repository, tag
            )
        ) from exc
    except urllib.error.URLError as exc:
        raise RegistryError(
            "cannot reach {0}: {1}".format(registry, exc.reason)
        ) from exc
    except TimeoutError as exc:
        raise RegistryError(
            "timed out after {0}s querying {1}".format(timeout, registry)
        ) from exc


# ---------------------------------------------------------------------------
# What one image *contains*, from its labels
# ---------------------------------------------------------------------------
#
# The HA images carry their own inventory as OCI labels, readable from the
# config blob -- a few KB behind an anonymous token, with no pull. That matters
# because the alternative is downloading multi-gigabyte images to answer a
# question about which extension versions they ship.
#
# The labels overstate. They are the union across the whole build, so a pg16
# image advertises TimescaleDB 2.12.2 even though 2.12 never supported pg16 and
# the image ships neither its shared object nor its install script. Callers must
# clamp the floor; see `drift.effective_floor`. Treat what comes back as a
# prediction that the filesystem can overrule.

_LABEL_PG_AVAILABLE = "com.timescaledb.image.postgresql.available_versions"
_LABEL_TS_AVAILABLE = "com.timescaledb.image.timescaledb.available_versions"
_LABEL_TS_DEFAULT = "com.timescaledb.image.timescaledb.version"
_LABEL_PG_DEFAULT = "com.timescaledb.image.postgresql.version"

_INDEX_TYPES = frozenset(
    {
        "application/vnd.oci.image.index.v1+json",
        "application/vnd.docker.distribution.manifest.list.v2+json",
    }
)


@dataclass(frozen=True)
class ImageLabels:
    """The inventory one image tag declares about itself."""

    reference: str
    pg_versions: Tuple[str, ...]
    ts_versions: Tuple[str, ...]
    pg_default: Optional[str]
    ts_default: Optional[str]

    @property
    def pg_majors(self) -> Tuple[int, ...]:
        majors = set()
        for version in self.pg_versions:
            try:
                majors.add(parse_version(version)[0])
            except InvalidVersion:
                continue
        return tuple(sorted(majors))

    @property
    def ts_floor(self) -> Optional[str]:
        return self._sorted_ts()[0] if self.ts_versions else None

    @property
    def ts_ceiling(self) -> Optional[str]:
        return self._sorted_ts()[-1] if self.ts_versions else None

    def _sorted_ts(self) -> List[str]:
        def key(v: str):
            try:
                return parse_version(v)
            except InvalidVersion:
                return (0,)

        return sorted(self.ts_versions, key=key)


def _split_versions(value: object) -> Tuple[str, ...]:
    """Split a label's version list.

    The labels use whitespace, but commas are cheap to tolerate and a label
    format change should degrade to a short list rather than one long junk
    string.
    """
    if not value:
        return ()
    text = str(value).replace(",", " ")
    return tuple(part for part in text.split() if part)


def _registry_token(registry: str, repository: str, timeout: float) -> Optional[str]:
    """An anonymous pull token, or None if the registry does not require one."""
    if registry != "registry-1.docker.io":
        return None
    doc = _get_json(
        _AUTH_URL.format(repo=repository), {"User-Agent": _USER_AGENT}, timeout
    )
    return doc.get("token") or doc.get("access_token")


def _fetch_manifest(url: str, headers: Dict[str, str], timeout: float) -> Any:
    request = urllib.request.Request(url, headers=headers)
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            return json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            raise RegistryError("no such image: {0}".format(url)) from exc
        raise RegistryError(
            "registry returned HTTP {0} for {1}".format(exc.code, url)
        ) from exc
    except urllib.error.URLError as exc:
        raise RegistryError("cannot reach {0}: {1}".format(url, exc.reason)) from exc
    except TimeoutError as exc:
        raise RegistryError(
            "timed out after {0}s querying {1}".format(timeout, url)
        ) from exc
    except json.JSONDecodeError as exc:
        raise RegistryError("registry returned non-JSON from {0}: {1}".format(url, exc)) from exc


def fetch_image_labels(reference: str, timeout: float = 15.0) -> ImageLabels:
    """Read an image's declared contents without pulling it.

    Three round trips: token, manifest (following the multi-arch index to the
    amd64 entry), then the config blob. The blob is served as a redirect to a
    CDN, so redirects must be followed -- urllib does that by default, which is
    the one place this is easier than curl.
    """
    registry, repository, tag = parse_image_reference(reference)
    token = _registry_token(registry, repository, timeout)

    headers = {"Accept": _MANIFEST_ACCEPT, "User-Agent": _USER_AGENT}
    if token:
        headers["Authorization"] = "Bearer " + token

    base = "https://{0}/v2/{1}".format(registry, repository)
    manifest = _fetch_manifest("{0}/manifests/{1}".format(base, tag), headers, timeout)

    if manifest.get("mediaType") in _INDEX_TYPES or "manifests" in manifest:
        digest = None
        for entry in manifest.get("manifests", []):
            platform = entry.get("platform") or {}
            if platform.get("architecture") == "amd64" and platform.get("os") == "linux":
                digest = entry.get("digest")
                break
        if not digest:
            raise RegistryError(
                "{0}: multi-arch index has no linux/amd64 entry".format(reference)
            )
        manifest = _fetch_manifest(
            "{0}/manifests/{1}".format(base, digest), headers, timeout
        )

    config_digest = (manifest.get("config") or {}).get("digest")
    if not config_digest:
        raise RegistryError("{0}: manifest carries no config digest".format(reference))

    blob = _fetch_manifest(
        "{0}/blobs/{1}".format(base, config_digest),
        {k: v for k, v in headers.items() if k != "Accept"},
        timeout,
    )
    labels = ((blob.get("config") or {}).get("Labels")) or {}

    return ImageLabels(
        reference=reference,
        pg_versions=_split_versions(labels.get(_LABEL_PG_AVAILABLE)),
        ts_versions=_split_versions(labels.get(_LABEL_TS_AVAILABLE)),
        pg_default=labels.get(_LABEL_PG_DEFAULT) or None,
        ts_default=labels.get(_LABEL_TS_DEFAULT) or None,
    )
